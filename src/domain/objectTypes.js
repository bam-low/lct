export const OBJECT_TYPE_LIST = Object.values(OBJECT_TYPES);

export function getObjectType(id) {
  return OBJECT_TYPES[id] ?? null;
}

// Выбранный вариант поля-списка (select) с его числовыми свойствами (speedFactor, slotsPerLane...).
export function selectOption(objectTypeId, key, value) {
  const field = getObjectType(objectTypeId)?.paramSchema.find((f) => f.key === key);
  return field?.options?.find((o) => o.value === value) ?? field?.options?.[0] ?? null;
}

export function defaultParamsFor(objectTypeId) {
  const type = getObjectType(objectTypeId);
  if (!type) return {};

  return Object.fromEntries(
    type.paramSchema.map((field) => [field.key, field.default])
  );
}
